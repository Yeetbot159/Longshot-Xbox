"""Write imports.inc: every Windows function a built Longshot imports (the game exe and longshot_vk.dll), so the probe
can ask the console which of them exist in the app container. Only API names go into the file, nothing of the game.

    python -I xbox/probe/gen_imports.py <game folder>/bin/longshot.exe <game folder>/bin/longshot_vk.dll

dumpbin comes from Visual Studio's build tools (found with vswhere); the C runtime's api-ms-win-crt-* sets are left out
(the probe links the C runtime statically), and so are libraries Longshot ships itself (SDL, wgpu-native).
"""
import os
import re
import subprocess
import sys

SKIP = re.compile(r"^(api-ms-win-crt-|sdl2|sdl3|wgpu_native|vulkan-1|longshot)", re.I)


def dumpbin():
    vswhere = os.path.join(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"),
                           "Microsoft Visual Studio", "Installer", "vswhere.exe")
    root = subprocess.run([vswhere, "-latest", "-products", "*", "-requires",
                           "Microsoft.VisualStudio.Component.VC.Tools.x86.x64", "-property", "installationPath"],
                          capture_output=True, text=True, check=True).stdout.strip()
    tools = os.path.join(root, "VC", "Tools", "MSVC")
    version = sorted(os.listdir(tools))[-1]
    return os.path.join(tools, version, "bin", "Hostx64", "x64", "dumpbin.exe")


def imports(tool, path):
    out = subprocess.run([tool, "/nologo", "/imports", path], capture_output=True, text=True, check=True).stdout
    dll, found = None, set()
    for line in out.splitlines():
        m = re.match(r"^\s{4}(\S+\.dll)$", line, re.I)
        if m:
            dll = m.group(1)
            continue
        m = re.match(r"^\s+[0-9A-Fa-f]+\s+([A-Za-z_]\w*)$", line)
        if m and dll and not SKIP.match(dll):
            found.add((dll.lower(), m.group(1)))
    return found


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    tool = dumpbin()
    found = set()
    for path in sys.argv[1:]:
        found |= imports(tool, path)
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "imports.inc"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by gen_imports.py: the Windows functions a built Longshot imports.\n")
        for dll, name in sorted(found):
            f.write('{"%s", "%s"},\n' % (dll, name))
    print("%d functions from %d libraries" % (len(found), len({d for d, _ in found})))
    return 0


if __name__ == "__main__":
    sys.exit(main())
